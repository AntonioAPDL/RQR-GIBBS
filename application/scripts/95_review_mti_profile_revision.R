#!/usr/bin/env Rscript
arguments <- commandArgs(FALSE)
script <- sub("--file=","",arguments[startsWith(arguments,"--file=")][1],fixed=TRUE)
setwd(normalizePath(file.path(dirname(script),"..",".."),mustWork=TRUE))
for(file in c("pharma_tolerance_application.R","pharma_mti_application.R",
              "mti_profile_revision.R","mti_profile_review.R"))
  source(file.path("application/scripts/lib",file))
args <- commandArgs(TRUE)
config_path <- pta_arg_value(args,"--config=","application/config/mti_profile_revision_20261021.json")
review_path <- pta_arg_value(args,"--review=","application/config/mti_profile_review_20261021.json")
run <- pta_arg_value(args,"--run-dir=","")
output <- pta_arg_value(args,"--output-dir=","application/outputs/mti_profile_review_20261021")
if(!nzchar(run))stop("Provide the explicit frozen study directory with --run-dir=.")
if(any(strsplit(output,"/",fixed=TRUE)[[1L]]==".."))stop("Output path cannot contain parent traversal.")
repo <- normalizePath(".")
absolute <- mpr_output_path(if(startsWith(output,"/"))output else file.path(repo,output))
allowed <- mpr_output_path(file.path(repo,"application","outputs"))
if(!startsWith(absolute,paste0(allowed,"/")))stop("Review output must be under application/outputs/.")
cfg <- jsonlite::read_json(config_path,simplifyVector=FALSE)
review <- jsonlite::read_json(review_path,simplifyVector=FALSE)
if("--health-only" %in% args) {
  frozen <- jsonlite::read_json(cfg$validation_config,simplifyVector=FALSE)
  print(mpr_health(normalizePath(run,mustWork=TRUE),cfg,frozen),row.names=FALSE)
  cat("Read-only progress snapshot; use a full report for checkpoint and statistical verification.\n")
  quit(status=0)
}
options(warn=2)
result <- mpr_build_report(run,absolute,cfg,review,repo,config_path,review_path)
cat("Assessment:",result$decision,"\nReport:",file.path(absolute,"REPORT.md"),"\n")
